/**
 * An icon as a string, for use inside a template literal.
 * Decorative by default — pass `title` when the icon is the only label on a control.
 */
export function icon(name, { size = 20, stroke = 1.75, cls = '', title = '' } = {}) {
  const body = ICONS[name];
  if (!body) return '';
  return `<svg class="ico${cls ? ` ${cls}` : ''}" viewBox="0 0 24 24" width="${size}" height="${size}" fill="none"
    stroke="currentColor" stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round"
    ${title ? `role="img" aria-label="${title.replace(/"/g, '&quot;')}"` : 'aria-hidden="true" focusable="false"'}>${body}</svg>`;
}

/** The same icon as a node. */
export function iconEl(name, opts) {
  const d = document.createElement('div');
  d.innerHTML = icon(name, opts);
  return d.firstElementChild;
}

/** Whether a name exists, so callers can fall back rather than render nothing. */
export const hasIcon = (name) => !!ICONS[name];
